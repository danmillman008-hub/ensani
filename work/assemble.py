def fx(s):
    s=s or ''
    s=s.replace('ي','ی').replace('ك','ک').replace('ۀ','ه')
    for a,b in [('اسالمي','اسلامی'),('ااسلمي','اسلامی'),('ااسلمی','اسلامی'),('اسالم','اسلام'),('ااسلم','اسلام'),
                ('کالم','کلام'),('عالمه','علامه'),('والیت','ولایت'),('گیالن','گیلان'),('ايالم','ایلام'),
                ('ساوجبالغ','ساوجبلاغ'),('ساوجبالغ','ساوجبلاغ'),('مالرد','ملارد'),('فرديس','فردیس'),
                ('ساوجبالغ','ساوجبلاغ'),('فرديس','فردیس'),('پرديس','پردیس'),('ایالم','ایلام'),('ااسلامی','اسلامی')]:
        s=s.replace(a,b)
    s=s.replace(')دانشگاه','دانشگاه').replace(')مؤسسه','مؤسسه').replace(')موسسه','موسسه')
    s=s.replace('دانشگاه بین المللی ) امام خمینی (ره','دانشگاه بین‌المللی امام خمینی(ره)')
    s=s.replace('دانشگاه بين المللی ) امام خمينی (ره','دانشگاه بین‌المللی امام خمینی(ره)')
    s=re.sub(r'\(س\(', '(س) ', s)
    s=s.replace('ویژه خواهران–','ویژه خواهران) –').replace('(ویژه خواهران','(ویژه خواهران)')
    s=s.replace('دانشگاه الزهرا (س) ویژه خواهران) – تهران','دانشگاه الزهرا(س) – تهران (ویژه خواهران)')
    s=s.replace('دانشگاه حضرت معصومه(س) ویژه خواهران)','دانشگاه حضرت معصومه(س) – قم (ویژه خواهران)')
    s=s.replace('دانشگاه خوارزمی (محل تحصیل تهران','دانشگاه خوارزمی – تهران').replace('(محل تحصیل تهران)','– تهران')
    s=s.replace('دانشگاه خوارزمی (محل تحصیل کرج','دانشگاه خوارزمی – کرج')
    s=s.replace('مؤسسه غیرانتفاعی آل طه (ویژه خواهران)','مؤسسه غیرانتفاعی آل طه – تهران (ویژه خواهران)')
    s=s.replace('مؤسسه غیرانتفاعی ابرار (ویژه خواهران)','مؤسسه غیرانتفاعی ابرار – تهران (ویژه خواهران)')
    s=re.sub(r'مؤسسه غیرانتفاعی ارشاد \(محل تحصیل واحد تهران\)?','مؤسسه غیرانتفاعی ارشاد – تهران',s)
    s=s.replace('موسسه غیرانتفاعی رسام ( ویژه خواهران) ـ کرج','مؤسسه غیرانتفاعی رسام – کرج (ویژه خواهران)')
    s=s.replace('موسسه غیرانتفاعی','مؤسسه غیرانتفاعی').replace('دانشگاه غیرانتفاعی','مؤسسه غیرانتفاعی')
    s=s.replace('دانشگاه ملی مهارت-','دانشگاه ملی مهارت –')
    s=re.sub(r'\(محل\)\)?تحصیل\s*','(محل تحصیل) ', s)
    s=re.sub(r'دانشگاه گنبد.*$','دانشگاه گنبد – دانشکده علوم انسانی آزادشهر (ویژه دختران)', s)
    s=s.replace('روان شناسی','روان‌شناسی').replace('مردم شناسی','مردم‌شناسی')
    s=re.sub(r'\(\s*\)',' ',s); s=s.replace('))',')').replace('((','(')
    s=re.sub(r'\s+',' ',s).strip(' -–,')
    # متوازن‌سازی پرانتزها
    if s.count('(') > s.count(')'): s=s+')'*(s.count('(')-s.count(')'))
    return s
