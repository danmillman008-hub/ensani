def inst_disp(x):
    s=fx(x['inst'])
    if x['ctype']=='پیامنور' and not s.startswith('دانشگاه پیام'):
        s='دانشگاه پیام‌نور – '+re.sub(r'^(مرکز|واحد)\s*','',s)
        s=s.replace('پیام‌نور – تهران غرب','پیام‌نور – تهران غرب').replace('پیام‌نور – ','پیام‌نور – ')
    if 'ولایت' in s and 'والیت' not in s: s='دانشگاه ولایت (ایرانشهر)'
    return s
