def city_of(x,inst):
    if x['city'].startswith('کرج') or x['city']=='البرز' or (x.get('province')=='البرز'): return 'کرج'
    for k,v in CITY.items():
        if k in inst:
            if k=='ملی مهارت':
                if 'شیراز' in inst: return 'شیراز'
                if 'گنبد' in inst: return 'گنبدکاووس'
                return '—'
            return v
    c=x['city'].replace('*L','لا')
    return c if c else '—'
def dore_of(x,inst):
    d=(x['dore'] or '').strip()
    if 'فرهنگیان' in inst: return 'روزانه – فرهنگیان (تعهد خدمت)'
    if d=='روزانه': return 'روزانه (دولتی)'
    if d=='نوبت دوم': return 'نوبت دوم (شبانه – شهریه)'
    if x['ctype']=='پیامنور': return 'پیام‌نور (شهریه‌پرداز)'
    if x['ctype']=='غیرانتفاعی': return 'غیرانتفاعی (شهریه‌پرداز)'
    if d: return fx(d)
    return '—'
def band(p):
    if p is None: return 'مشروط'
    if p>=90: return 'بیش از ۹۰٪ (نزدیک به مطمئن)'
    if p>=70: return '۷۰–۹۰٪ (بالا)'
    if p>=45: return '۴۵–۷۰٪ (متوسط)'
    if p>=20: return '۲۰–۴۵٪ (کم)'
    return 'زیر ۲۰٪ (خیلی کم)'
