def sh(t): return get_display(reshape(t))
def wid(t,size,f=FR): return f.text_length(sh(t), size)
def fa2en(s):
    for i,d in enumerate('۰۱۲۳۴۵۶۷۸۹'): s=s.replace(d,str(i))
    return s
def en2fa(s):
    for i,d in enumerate('0123456789'): s=str(s).replace(d,'۰۱۲۳۴۵۶۷۸۹'[i])
    return s
def num(n):
    s=f"{n:,}".replace(',','٬'); return en2fa(s)

class Doc:
    def __init__(self, title):
        self.doc=fitz.open(); self.title=title
        self.page=None; self.y=0
        self.first=True
        self.new_page()
    def new_page(self):
        self.page=self.doc.new_page(width=PW,height=PH)
        self.page.insert_font(fontname="VR", fontfile=FONT_R)
        self.page.insert_font(fontname="VB", fontfile=FONT_B)
        self.y=TOP
    def need(self,h):
        if self.y+h > BOT: self.new_page()
    def rtext(self, x_right, y_baseline, t, size=9.5, bold=False, color=INK):
        vis=sh(t); w=(FB if bold else FR).text_length(vis,size)
        self.page.insert_text((x_right-w, y_baseline), vis, fontname=("VB" if bold else "VR"), fontsize=size, color=color)
    def para(self, text, size=9.5, bold=False, color=INK, indent=0, gap=5, lh=1.62, x_right=None):
        xr = x_right if x_right is not None else CR
        lines=self.wrap(text, xr-indent-CL, size, FB if bold else FR)
        h=len(lines)*size*lh
        self.need(h+gap)
        for l in lines:
            self.y += size*lh
            self.rtext(xr-indent, self.y-size*lh*0.22, l, size=size, bold=bold, color=color)
        self.y += gap
    def wrap(self,text,maxw,size,f=FR):
        words=str(text).split(); lines=[]; cur=''
        for w in words:
            t=(cur+' '+w).strip()
            if f.text_length(sh(t),size)<=maxw: cur=t
            else:
                if cur: lines.append(cur)
                cur=w
        if cur: lines.append(cur)
        return lines or ['']
    def gapy(self,h=6): self.y+=h
    def rule(self,color=(0.80,0.82,0.87),pad=4):
        self.need(pad*2); self.y+=pad
        self.page.draw_line((CL,self.y),(CR,self.y),color=color,width=0.8); self.y+=pad
    def h1(self,text, gap_before=8, fill=NAVY):
        self.gapy(gap_before); h=24
        self.need(h+8)
        self.page.draw_rect(fitz.Rect(CL,self.y,CR,self.y+h), color=None, fill=fill)
        self.rtext(CR-9, self.y+h-7.5, text, size=11, bold=True, color=(1,1,1))
        self.y+=h+6
    def h2(self,text,gap_before=7):
        self.gapy(gap_before); self.need(19)
        vis=sh(text); w=FB.text_length(vis,10)
        self.page.insert_text((CR-w, self.y+11), vis, fontname="VB", fontsize=10, color=NAVY)
        self.page.draw_line((CR-w-4,self.y+15.5),(CR,self.y+15.5),color=NAVY,width=1.1)
        self.y+=20
    def bullet(self,text,size=9.5,color=INK,gap=3.5):
        self.para('•  '+text,size=size,color=color,indent=8,gap=gap,lh=1.62)
    def table(self, headers, rows, colw, size=8.0, head_size=8.2, colors=None, zebra=True, first_bold=True):
        assert abs(sum(colw)-(CR-CL))<8, (sum(colw),CR-CL)
        xr=[CR]
        for w in colw: xr.append(xr[-1]-w)
        hdrc=[head_size]*len(headers)
        self._head(headers,colw,head_size,xr)
        for i,row in enumerate(rows):
            cells=[self.wrap(str(c), colw[j]-10, size, FB if (first_bold and j==0) else FR) for j,c in enumerate(row)]
            nl=max(len(c) for c in cells); rh=nl*size*1.42+6
            if self.y+rh > BOT-6:
                self.new_page(); self._head(headers,colw,head_size,xr)
            if zebra and i%2==1:
                self.page.draw_rect(fitz.Rect(CL,self.y,CR,self.y+rh), color=None, fill=(0.965,0.972,0.985))
            self.page.draw_line((CL,self.y),(CR,self.y),color=(0.86,0.88,0.93),width=0.5)
            for j,lines in enumerate(cells):
                col=(0.33,0.35,0.45) if (colors or {}).get(j)=='dim' else INK
                if (colors or {}).get(j)=='code': col=(0.05,0.20,0.45)
                if (colors or {}).get(j)=='chance': col=self.chance_color(''.join(lines))
                fnt="VB" if (first_bold and j==0) else "VR"
                for k,l in enumerate(lines):
                    yy=self.y+size+2+k*size*1.42
                    vis=sh(l); w=(FB if (first_bold and j==0) else FR).text_length(vis,size)
                    self.page.insert_text((xr[j]-5-w, yy), vis, fontname=fnt, fontsize=size, color=col)
            self.y+=rh
        self.page.draw_line((CL,self.y),(CR,self.y),color=(0.86,0.88,0.93),width=0.5)
        self.y+=6
    def _head(self,headers,colw,head_size,xr):
        hh=head_size*1.5+7
        self.need(hh+34)
        self.page.draw_rect(fitz.Rect(CL,self.y,CR,self.y+hh), color=None, fill=(0.83,0.89,0.95))
        for j,h in enumerate(headers):
            vis=sh(h); w=FR.text_length(vis,head_size)
            self.page.insert_text((xr[j]-5-w, self.y+head_size+4), vis, fontname="VB", fontsize=head_size, color=(0.09,0.24,0.42))
        self.y+=hh
    @staticmethod
    def chance_color(txt):
        if 'مشروط' in txt: return (0.35,0.35,0.55)
        m=re.search(r'[\d۰-۹]+', txt)
        n=int(fa2en(m.group(0))) if m else 0
        if n>=90: return (0.03,0.44,0.16)
        if n>=70: return (0.08,0.50,0.20)
        if n>=45: return (0.72,0.46,0.0)
        if n>=20: return (0.78,0.27,0.05)
        return (0.66,0.15,0.15)
    def finish(self, foot_left, foot_right):
        for i,pg in enumerate(self.doc):
            nxt=f"صفحه {en2fa(str(i+1))} از {en2fa(str(len(self.doc)))}"
            vis=sh(nxt); w=FR.text_length(vis,8)
            pg.insert_text((PW/2-w/2, PH-22), vis, fontname="VR", fontsize=8, color=(0.45,0.45,0.52))
            for j,(txt,size) in enumerate([(foot_left,7),(foot_right,7)]):
                vis=sh(txt); w=FR.text_length(vis,size)
                x = CR-w if j==0 else CL
                pg.insert_text((x, PH-22), vis, fontname="VR", fontsize=size, color=(0.58,0.58,0.64))
            pg.draw_line((CL,PH-32),(CR,PH-32),color=(0.85,0.87,0.9),width=0.6)

